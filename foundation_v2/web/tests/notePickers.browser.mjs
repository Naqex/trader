import assert from 'node:assert/strict'
import {chromium} from 'playwright'
import {mkdir,writeFile} from 'node:fs/promises'

const [origin,out,api]=process.argv.slice(2)
for(const value of [origin,api]){assert.equal(new URL(value).hostname,'127.0.0.1');assert(!['5180','8010'].includes(new URL(value).port))}
await mkdir(out,{recursive:true})
const browser=await chromium.launch(),client=await browser.newContext()
const report={scope:'Shared picker + note types; disposable native Router/PostgreSQL only',cases:[],errors:[]}
let activePage
const native=async(path,body)=>{
  const response=await client.request.fetch(api+path,{method:body?'POST':'GET',headers:{'X-Workspace-Id':'tenant-a','Idempotency-Key':crypto.randomUUID()},data:body})
  assert(response.ok(),await response.text());return response.json()
}
try {
  const fixture=await native('/fixture')
  for(const [width,theme,lang] of [[1920,'dark','en'],[1440,'light','en'],[390,'dark','vi']]){
    const vi=lang==='vi',label=(a,b)=>vi?a:b
    const context=await browser.newContext({viewport:{width,height:940},reducedMotion:'reduce'})
    await context.addInitScript(theme=>{localStorage.setItem('tw-theme',theme);localStorage.setItem('tw-timezone','Asia/Ho_Chi_Minh')},theme)
    await context.routeWebSocket('**/*',socket=>socket.close())
    let failTypes=false
    await context.route('**/*',async route=>{
      const url=new URL(route.request().url())
      if(url.origin!==origin)return route.abort()
      if(url.pathname==='/api/v2/events')return route.fulfill({status:204,body:''})
      if(url.pathname==='/api/v2/live/status')return route.fulfill({json:fixture.live_payload})
      if(url.pathname==='/api/v2/note-types'&&failTypes)return route.fulfill({status:503,json:{detail:'fixture_unavailable'}})
      if(url.pathname.startsWith('/api/'))return route.fulfill({response:await route.fetch({url:api+url.pathname+url.search})})
      return route.continue()
    })
    const page=await context.newPage();activePage=page;page.setDefaultTimeout(12000)
    page.on('pageerror',error=>report.errors.push(error.stack));page.on('console',message=>{if(message.type()==='error')report.lastConsoleError=message.text()})
    await page.goto(`${origin}/?workspace=tenant-a&view=live&area=live&section=notes&lang=${lang}`)
    await page.locator('.live-note-create').click()
    const drawer=page.locator('.is-note-editor'),editor=drawer.locator('.bn-editor')
    await editor.waitFor();await drawer.getByRole('textbox',{name:label('Tiêu đề','Title'),exact:true}).fill(`Picker ${width}`)
    await editor.fill('Date and type persistence')
    await drawer.locator('[data-state=saved]').waitFor()
    const type=drawer.getByRole('button',{name:label('Loại ghi chú','Note type'),exact:true}),menu=page.locator('.wm-note-type-menu')
    await type.click();await menu.getByRole('option').first().waitFor()
    assert.equal(await menu.getByRole('option').count(),4)
    await menu.getByRole('button',{name:label('Sửa loại ghi chú Chung','Edit note type General'),exact:true}).click()
    const edit=page.locator('.wm-label-edit-popup')
    await edit.waitFor();assert.equal(await edit.getByRole('button',{name:label('Xóa loại ghi chú','Delete note type'),exact:true}).count(),0)
    await edit.getByRole('button',{name:label('Xanh dương','Blue'),exact:true}).click()
    await page.waitForFunction(()=>document.querySelector('.wm-label-edit-popup [aria-pressed=true]')===document.activeElement && !document.activeElement.disabled)
    assert.equal((await native('/api/v2/note-types')).items.find(item=>item.id==='general').name,'General','Changing builtin color must preserve its translated default name')
    await page.keyboard.press('Escape');assert(await menu.isVisible());assert(await drawer.isVisible())
    const search=menu.getByRole('searchbox')
    await search.fill(`Custom ${width}`);await search.press('Enter');await menu.waitFor({state:'detached'})
    await drawer.locator('[data-state=saved]').waitFor()
    let catalog=await native('/api/v2/note-types'),custom=catalog.items.find(item=>item.name===`Custom ${width}`)
    assert(custom&&!custom.archived)
    const records=await native('/api/v2/live/records'),note=records.items.find(item=>item.payload.title===`Picker ${width}`)
    assert.equal(note.payload.note_type,custom.id)
    const range=drawer.getByRole('textbox',{name:label('Khoảng ngày','Date range'),exact:true})
    await range.fill('01/10/2026 – 30/10/2026');await range.press('Tab');await drawer.locator('[data-state=saved]').waitFor()
    await range.fill('31/02/2026 – 30/10/2026');await range.press('Tab')
    assert.equal(await range.getAttribute('aria-invalid'),'true')
    assert.equal((await native('/api/v2/live/records')).items.find(item=>item.record_id===note.record_id).payload.review_from,'2026-10-01')
    await range.fill('01/10/2026 – 30/10/2026')
    await drawer.getByRole('button',{name:label('Chọn khoảng ngày','Choose date range'),exact:true}).click()
    const calendar=page.locator('.project-date-popover:popover-open')
    await calendar.getByRole('gridcell',{name:'20/10/2026',exact:true}).click()
    assert.equal((await native('/api/v2/live/records')).items.find(item=>item.record_id===note.record_id).payload.review_to,'2026-10-30','First range click must not autosave a partial range')
    await calendar.getByRole('gridcell',{name:'15/10/2026',exact:true}).click()
    await drawer.locator('[data-state=saved]').waitFor()
    assert.equal(await range.inputValue(),'15/10/2026 – 20/10/2026')
    await page.reload();await page.locator('.live-note-row').filter({hasText:`Picker ${width}`}).click();await editor.waitFor()
    assert.equal(await range.inputValue(),'15/10/2026 – 20/10/2026')
    await type.getByText(`Custom ${width}`,{exact:true}).waitFor()
    await type.click();await menu.getByRole('button',{name:label(`Sửa loại ghi chú Custom ${width}`,`Edit note type Custom ${width}`),exact:true}).click();await edit.waitFor()
    await page.screenshot({path:`${out}/type-menu-${width}-${theme}.png`})
    const bounds=await edit.boundingBox();assert(bounds.x>=0&&bounds.x+bounds.width<=width+1)
    await edit.getByRole('textbox').fill(`Renamed ${width}`);await edit.getByRole('textbox').press('Enter');await edit.waitFor({state:'detached'})
    await menu.getByRole('button',{name:label(`Sửa loại ghi chú Renamed ${width}`,`Edit note type Renamed ${width}`),exact:true}).click();await edit.waitFor()
    const blue=edit.getByRole('button',{name:label('Xanh dương','Blue'),exact:true})
    await blue.click();await page.waitForFunction(()=>document.querySelector('.wm-label-edit-popup [aria-pressed=true]')?.textContent.includes('Blue')||document.querySelector('.wm-label-edit-popup [aria-pressed=true]')?.textContent.includes('Xanh dương'))
    assert.equal((await native('/api/v2/note-types')).items.find(item=>item.id===custom.id).color,'blue')
    await edit.getByRole('button',{name:label('Xóa loại ghi chú','Delete note type'),exact:true}).click()
    await edit.getByRole('button',{name:label('Xóa loại ghi chú','Delete note type'),exact:true}).click();await edit.waitFor({state:'detached'})
    assert((await native('/api/v2/note-types')).items.find(item=>item.id===custom.id).archived)
    assert.equal(await menu.getByRole('option').count(),4)
    await page.keyboard.press('Escape');await drawer.locator('[data-state=saved]').waitFor()
    if(width===1920){
      failTypes=true;await page.reload();await page.locator('.live-note-row').filter({hasText:`Picker ${width}`}).click();await editor.waitFor();await type.click()
      await menu.getByRole('alert').waitFor();assert(await menu.getByRole('option').first().isDisabled())
      failTypes=false;await menu.getByRole('button',{name:'Reload data',exact:true}).click();await menu.getByRole('option').first().waitFor();await page.waitForFunction(()=>!document.querySelector('.wm-note-type-menu [role=option]').disabled)
      await page.keyboard.press('Escape')
    }
    await page.screenshot({path:`${out}/note-${width}-${theme}.png`})
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false)
    report.cases.push({width,theme,lang,name:'protected defaults, custom create/save/reload/rename/archive, invalid range retained, two-click range commit',bounds})
    await page.goto(`${origin}/?workspace=tenant-a&view=trade&area=testing&ui_reference=1&lang=vi`)
    await page.getByRole('button',{name:'Mở dialog tương tác',exact:true}).click()
    const dialog=page.getByRole('dialog',{name:'Dialog tương tác mẫu',exact:true})
    const instant=dialog.getByRole('textbox',{name:'Thời điểm trong dialog',exact:true})
    await instant.fill('20/10/2026 17:00:00');await instant.press('Tab');assert.notEqual(await instant.getAttribute('aria-invalid'),'true')
    await instant.fill('20/10/2026 17:00:01');await instant.press('Tab');assert.equal(await instant.getAttribute('aria-invalid'),'true')
    await instant.fill('20/10/2026 10:30:45');await dialog.getByRole('button',{name:'Chọn ngày',exact:true}).first().click()
    await calendar.getByRole('spinbutton',{name:'Phút',exact:true}).fill('31')
    await calendar.getByRole('button',{name:'Xong',exact:true}).click();assert.equal(await instant.inputValue(),'20/10/2026 10:31:45')
    const time=dialog.getByRole('textbox',{name:'Giờ trong dialog',exact:true})
    await dialog.getByRole('button',{name:'Chọn giờ',exact:true}).click();await calendar.getByRole('spinbutton',{name:'Giây',exact:true}).press('ArrowUp');await page.keyboard.press('Escape')
    assert.equal(await time.inputValue(),'10:30:46');assert(await dialog.isVisible())
    await dialog.getByRole('button',{name:'Chọn khoảng ngày',exact:true}).click();await calendar.waitFor()
    await page.screenshot({path:`${out}/shared-calendar-${width}-${theme}.png`})
    const box=await calendar.boundingBox();assert(box.x>=0&&box.x+box.width<=width+1&&box.y>=0&&box.y+box.height<=940+1)
    await calendar.getByRole('gridcell',{name:'31/10/2026',exact:true}).focus()
    await page.keyboard.press('ArrowRight');await page.waitForFunction(()=>document.activeElement?.dataset.date==='2026-11-01')
    await page.keyboard.press('PageUp');await page.waitForFunction(()=>document.activeElement?.dataset.date==='2026-10-01')
    await page.keyboard.press('Home');await page.waitForFunction(()=>document.activeElement?.dataset.date==='2026-09-27')
    assert.equal(await dialog.getByRole('textbox',{name:'Khoảng ngày trong dialog',exact:true}).inputValue(),'20/10/2026 – 25/10/2026','Keyboard navigation alone cannot commit dates')
    await page.keyboard.press('Escape');assert(await dialog.isVisible())
    await page.keyboard.press('Escape');await dialog.waitFor({state:'detached'})
    report.cases.push({width,name:'shared date/time/datetime/range, bounds, seconds, nested Escape, viewport containment',box})
    await context.close()
  }
  assert.deepEqual(report.errors,[]);report.status='PASS'
}catch(error){report.status='FAIL';report.failure=error.stack;if(activePage){report.snapshot=await activePage.locator('body').innerText().catch(()=>null);await activePage.screenshot({path:`${out}/failure.png`}).catch(()=>{})}throw error}
finally{await writeFile(`${out}/report.json`,JSON.stringify(report,null,2));await browser.close()}
