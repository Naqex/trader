import assert from 'node:assert/strict'
import { chromium } from 'playwright'
import { mkdir,writeFile } from 'node:fs/promises'
const [origin,out]=process.argv.slice(2)
assert.equal(new URL(origin).hostname,'127.0.0.1')
await mkdir(out,{recursive:true})
const report={scope:'Local demo Sessions/Prop UI; no broker/API writes',cases:[],errors:[],writes:[]}
const browser=await chromium.launch();let page
try {
 for(const [width,theme] of [[1440,'dark'],[390,'light']])for(const source of ['sessions','prop']){
  const ctx=await browser.newContext({viewport:{width,height:940},reducedMotion:'reduce'})
  await ctx.addInitScript(theme=>localStorage.setItem('tw-theme',theme),theme)
  await ctx.routeWebSocket('**/*',s=>s.close())
  await ctx.route('**/*',route=>{const req=route.request(),url=new URL(req.url());if(url.origin!==origin)return route.abort();if(!['GET','HEAD','OPTIONS'].includes(req.method())){report.writes.push(url.pathname);return route.abort()}if(url.pathname.startsWith('/api/'))return route.fulfill({json:{items:[],available:false}});return route.continue()})
  page=await ctx.newPage();page.setDefaultTimeout(10000);page.on('pageerror',e=>report.errors.push(e.message))
  await page.goto(`${origin}/?workspace=fixture&view=analytics&area=testing&section=analytics&lang=vi&demo=1&analytics_source=${source}&analytics_tab=simulation`)
  const panel=page.getByTestId('monte-carlo-simulator');await panel.waitFor()
  const primary=panel.locator('.fxa-monte-controls > .fxa-field input')
  assert.equal(await primary.count(),6)
  const initial=await primary.evaluateAll(els=>els.map(el=>el.value));assert(Number(initial[2])>0)
  assert.deepEqual(initial.slice(0,2),['100','100']);assert(initial.every(value=>value!==''))
  assert.equal(await panel.locator('.fxa-monte-output').count(),1)
  assert.equal(await panel.locator('.fxa-monte-advanced').count(),0)
  assert.equal(await panel.locator('.fxa-monte-metrics .fxa-metric').count(),8)
  assert.match(await panel.locator('.fxa-monte-metrics .fxa-metric').first().locator('strong').innerText(),/^0(?:\s|$)/)
  assert.equal(await panel.locator('.fxa-monte-output .fxa-line-viz svg').count(),1)
  assert.equal(await panel.locator('.fxa-line-viz svg path,.fxa-line-viz svg circle').count(),0,'No invented path, fill or points before a run')
  assert.deepEqual(await panel.locator('.fxa-x-tick text').allTextContents(),['0'])
  assert.equal(await panel.locator('.fxa-axis-title').count(),0)
  assert.match(await panel.locator('.fxa-line-viz svg').textContent(),/\$0/)
  const emptyAxis=await panel.locator('.fxa-line-viz svg').evaluate(el=>{const line=el.querySelector('.fxa-gridline'),tick=el.querySelector('.fxa-x-tick text');return {lines:el.querySelectorAll('.fxa-gridline').length,centered:Math.abs(Number(tick.getAttribute('x'))-(Number(line.getAttribute('x1'))+Number(line.getAttribute('x2')))/2)<1}})
  assert.equal(emptyAxis.lines,1);assert(emptyAxis.centered)
  const geometry=await panel.locator('.fxa-monte-metrics').evaluate(el=>{const r=el.getBoundingClientRect(),p=el.closest('.fxa-section-body').getBoundingClientRect(),cells=[...el.children];return {gap:getComputedStyle(el).gap,flushLeft:Math.abs(r.left-p.left)<2,flushRight:Math.abs(r.right-p.right)<2,radii:cells.map(cell=>getComputedStyle(cell).borderRadius),separators:cells.slice(1).some(cell=>getComputedStyle(cell).borderTopWidth==='1px')}})
  assert.equal(geometry.gap,'0px');assert(geometry.flushLeft&&geometry.flushRight);assert(geometry.radii.every(radius=>radius==='0px'));assert(geometry.separators)
  await panel.scrollIntoViewIfNeeded();await page.screenshot({path:`${out}/${source}-${width}-initial.png`})
  await primary.nth(3).fill('');await panel.getByRole('button',{name:'Chạy mô phỏng',exact:true}).click()
  await primary.nth(3).getAttribute('aria-invalid').then(value=>assert.equal(value,'true'))
  assert.match(await panel.locator('.wm-field-error').innerText(),/Nhập/)
  await page.waitForFunction(()=>document.activeElement?.name==='averageWin')
  assert.equal(await panel.locator('svg [data-series]').count(),0)
  await page.screenshot({path:`${out}/${source}-${width}-validation.png`})
  await primary.nth(3).fill(initial[3]);assert.equal(await panel.locator('.wm-field-error').count(),0)
  await primary.nth(0).fill('1000');await primary.nth(1).fill('1000');await panel.getByRole('button',{name:'Chạy mô phỏng',exact:true}).click()
  assert.match(await panel.locator('.wm-field-error').innerText(),/250.000/)
  assert.equal(await panel.locator('svg [data-series]').count(),0)
  await primary.nth(0).fill(initial[0]);await primary.nth(1).fill(initial[1])
  await panel.getByRole('button',{name:'Chạy mô phỏng',exact:true}).click()
  await panel.getByRole('button',{name:'Chạy lại',exact:true}).waitFor()
  const paths=await panel.locator('svg [data-series] > path').evaluateAll(els=>els.map(el=>el.getAttribute('d')))
  assert.equal(paths.length,Math.min(30,Number(initial[0])))
  assert(new Set(paths).size>1,'Measured defaults produce distinct random paths')
  const colors=await panel.locator('svg [data-series] > path').evaluateAll(els=>els.slice(0,6).map(el=>getComputedStyle(el).stroke))
  assert.equal(new Set(colors).size,6,'First six runs use distinct theme palette colors')
  assert(paths.every(d=>!d.includes('C')),'Trade outcomes use straight segments')
  await panel.scrollIntoViewIfNeeded();await page.screenshot({path:`${out}/${source}-${width}-random-paths.png`})
  await panel.getByRole('button',{name:'Đặt lại',exact:true}).click()
  assert.equal(await panel.locator('.fxa-monte-output').count(),1)
  assert.match(await panel.locator('.fxa-monte-metrics .fxa-metric').first().locator('strong').innerText(),/^0(?:\s|$)/)
  for(const [i,value]of ['3','4','1000','20','10','0'].entries())await primary.nth(i).fill(value)
  await panel.getByRole('button',{name:'Chạy mô phỏng',exact:true}).click()
  await panel.getByRole('button',{name:'Chạy lại',exact:true}).waitFor()
  const metrics=panel.locator('.fxa-monte-metrics .fxa-metric');await metrics.first().waitFor()
  assert.equal(await metrics.count(),8)
  assert.equal(await metrics.nth(3).locator('strong').innerText(),'0')
  assert.equal(await metrics.nth(4).locator('strong').innerText(),'0')
  assert.equal(await metrics.nth(6).locator('strong').innerText(),'0')
  const firstRunLosses = await metrics.nth(7).locator('strong').innerText()
  assert.match(firstRunLosses,/^\d/)
  assert.match(await metrics.nth(5).locator('strong').innerText(),/^\d/)
  assert.equal(await panel.locator('svg [data-series]').count(),3)
  assert.equal(await panel.locator('.fxa-x-tick text').first().textContent(),'0')
  // The shared report remains mounted when changing analytics tabs.
  await page.locator('#fxa-tab-performance').click();await page.locator('#fxa-tab-simulation').click()
  assert.equal(await metrics.nth(7).locator('strong').innerText(),firstRunLosses)
  await primary.nth(2).fill('25');await primary.nth(5).fill('100')
  await panel.getByText('Cấu hình đã đổi; chạy lại để cập nhật kết quả.',{exact:true}).waitFor()
  await panel.getByRole('button',{name:'Chạy lại',exact:true}).click();await page.waitForFunction(() => document.querySelector('[data-testid="monte-carlo-simulator"] .fxa-monte-metrics .fxa-metric:nth-child(8) strong')?.textContent?.trim() === '0')
  assert.equal(await metrics.nth(5).locator('strong').innerText(),'0')
  assert.equal(await metrics.nth(7).locator('strong').innerText(),'0')
  assert.match(await metrics.nth(6).locator('strong').innerText(),/^\d/)
  assert.match(await metrics.nth(3).locator('strong').innerText(),/^(?:∞|0)$/)
  await panel.scrollIntoViewIfNeeded();await page.screenshot({path:`${out}/${source}-${width}-result.png`})
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth+1),false)
  await panel.getByRole('button',{name:'Đặt lại',exact:true}).click();assert.equal(await panel.locator('.fxa-monte-output').count(),1)
  assert.match(await panel.locator('.fxa-monte-metrics .fxa-metric').first().locator('strong').innerText(),/^0(?:\s|$)/)
  assert.deepEqual(await primary.evaluateAll(els=>els.map(el=>el.value)),initial)
  report.cases.push({width,theme,source,sixInputs:true,eightMetrics:true,measuredNormalDefaults:true,ruinStopsTrades:true,reset:true,tabPersistence:true})
  await ctx.close()
 }
 assert.deepEqual(report.errors,[]);assert.deepEqual(report.writes,[]);report.status='PASS'
}catch(e){report.status='FAIL';report.failure=e.stack;process.exitCode=1;await page?.screenshot({path:out+'/failure.png'}).catch(()=>{})}finally{await browser.close();await writeFile(out+'/report.json',JSON.stringify(report,null,2))}
console.log(JSON.stringify(report))
