import assert from 'node:assert/strict'
import { mkdir, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { chromium } from 'playwright'

const origin=process.env.TW_UI_ORIGIN
assert.ok(origin, 'Set TW_UI_ORIGIN to the isolated candidate preview')
assert.equal(new URL(origin).hostname,'127.0.0.1')
const out=path.resolve(process.env.TW_UI_EVIDENCE || '../evidence/owner-system-audit-20261031/foundations')
await mkdir(out,{recursive:true})
const report={scope:'UI Reference fixture; every API response is a labeled 503 fixture, events 204; no owner runtime or persisted writes',cases:[],errors:[],blocked:[]}
const browser=await chromium.launch({headless:true})
const colorChannels=color=>(color.match(/[\d.]+/g) || []).slice(0,3).map(Number)
const luminance=color=>colorChannels(color).map(value=>value/255).map(value=>value<=.04045?value/12.92:((value+.055)/1.055)**2.4).reduce((sum,value,index)=>sum+value*[.2126,.7152,.0722][index],0)
const contrast=(a,b)=>(Math.max(luminance(a),luminance(b))+.05)/(Math.min(luminance(a),luminance(b))+.05)
const checkboxStyle=locator=>locator.evaluate(node=>{const s=getComputedStyle(node),mark=getComputedStyle(node,'::after');return {background:s.backgroundColor,border:s.borderTopColor,mark:mark.backgroundColor,content:mark.content,outline:s.outlineStyle,outlineWidth:s.outlineWidth,width:node.getBoundingClientRect().width}})
try {
  for(const theme of ['dark','light']) for(const width of [1440,390]) {
    const context=await browser.newContext({viewport:{width,height:940},reducedMotion:'reduce'})
    await context.addInitScript(theme=>{localStorage.setItem('tw-theme',theme);localStorage.setItem('tw-language','vi')},theme)
    await context.route('**/*',route=>{
      const request=route.request(),url=new URL(request.url())
      if(url.origin!==origin || !['GET','HEAD','OPTIONS'].includes(request.method())) { report.blocked.push({method:request.method(),path:url.pathname});return route.abort() }
      if(url.pathname==='/api/v2/events') return route.fulfill({status:204,body:''})
      if(url.pathname.startsWith('/api/')) return route.fulfill({status:503,json:{detail:'owner_audit_labeled_unavailable_fixture'}})
      return route.continue()
    })
    const page=await context.newPage()
    page.setDefaultTimeout(12000)
    page.on('pageerror',error=>report.errors.push(error.message))
    await page.goto(`${origin}/?workspace=tenant-a&view=overview&area=testing&ui_reference=1`)
    const root=page.locator('.wm-component-reference')
    await root.waitFor()
    const size=property=>root.locator(`[data-token="${property}"] td:nth-child(2)`)
    const desktop=width>480,control=desktop?'32px':'44px',icon=desktop?'28px':'44px',gutter=desktop?'24px':'16px'
    await page.waitForFunction(({control,gutter})=>document.querySelector('[data-token="--wm-control-height"] td:nth-child(2)')?.textContent===control && document.querySelector('[data-token="--wm-page-gutter"] td:nth-child(2)')?.textContent===gutter,{control,gutter})
    assert.equal(await size('--wm-icon-action-size').innerText(),icon)
    assert.equal(await root.locator('#controls .wm-button.is-icon').first().evaluate(node=>node.getBoundingClientRect().height),parseFloat(icon))
    const checked=root.locator('#controls .wm-reference-choices input[type=checkbox]').first()
    const normal=await checkboxStyle(checked)
    assert.ok(contrast(normal.mark,normal.background)>=3,`Check mark contrast ${theme}`)
    assert.equal(normal.width,16)
    await checked.focus()
    const focused=await checkboxStyle(checked)
    assert.equal(focused.outline,'solid')
    assert.equal(focused.outlineWidth,'2px')
    const mixed=root.locator('#controls .wm-reference-choices input[type=checkbox]').nth(1)
    assert.equal(await mixed.evaluate(node=>node.indeterminate),true)
    assert.notEqual((await checkboxStyle(mixed)).content,'none')
    const disabled=root.locator('#controls .wm-reference-choices input[type=checkbox]:disabled')
    const locked=await checkboxStyle(disabled)
    await disabled.hover()
    assert.deepEqual(await checkboxStyle(disabled),locked,'Disabled hover preserves appearance')
    const selected=root.locator('.wm-reference-row-sample tr.is-selected'), selectedBox=await selected.boundingBox()
    const selectedBackground=await selected.evaluate(node=>getComputedStyle(node).backgroundColor)
    await selected.locator('td').first().hover()
    assert.equal(await selected.evaluate(node=>getComputedStyle(node).backgroundColor),selectedBackground,'Selected+hover retains selection')
    assert.equal((await selected.boundingBox()).height,selectedBox.height,'Hover does not change row height')
    const action=selected.getByRole('button'),actionBefore=await action.evaluate(node=>getComputedStyle(node).backgroundColor)
    await action.hover()
    await page.waitForFunction(node=>getComputedStyle(node).backgroundColor!=='rgba(0, 0, 0, 0)',await action.elementHandle())
    assert.notEqual(await action.evaluate(node=>getComputedStyle(node).backgroundColor),actionBefore,'Nested action has its own hover')
    await root.locator('#controls').screenshot({path:path.join(out,`controls-${theme}-${width}.png`),animations:'disabled'})
    if(desktop) {
      await page.setViewportSize({width:768,height:940})
      await page.waitForFunction(()=>document.querySelector('[data-token="--wm-page-gutter"] td:nth-child(2)')?.textContent==='20px')
      await page.setViewportSize({width,height:940})
      await page.waitForFunction(()=>document.querySelector('[data-token="--wm-page-gutter"] td:nth-child(2)')?.textContent==='24px')
    }
    await root.locator('#overlays > .wm-reference-controls > button').first().click()
    const modal=page.locator('.wm-reference-portal-dialog'),portalCheck=modal.locator('input[type=checkbox]').first()
    const unchecked=await checkboxStyle(portalCheck)
    await portalCheck.check()
    const portal=await checkboxStyle(portalCheck)
    assert.equal(portal.background,normal.background)
    assert.equal(portal.mark,normal.mark,'Portal and shell check use same foreground')
    assert.notEqual(portal.content,'none')
    assert.notEqual(unchecked.background,'rgba(0, 0, 0, 0)','Unchecked portal checkbox retains the canvas background')
    const portalIcon=modal.locator('.wm-button.is-icon')
    assert.equal(await portalIcon.evaluate(node=>node.getBoundingClientRect().height),parseFloat(icon))
    await portalCheck.uncheck()
    await modal.locator('.fx-select').last().getByRole('button').first().click()
    const menu=modal.locator('.fx-select-menu')
    const mark=menu.locator('.fx-select-checkbox.is-checked').first()
    const option=await checkboxStyle(mark)
    assert.notEqual(option.content,'none','Portal multiselect renders check mark')
    assert.equal(option.mark,normal.mark)
    assert.equal(option.width,16)
    await page.keyboard.press('Escape')
    await modal.screenshot({path:path.join(out,`portal-${theme}-${width}.png`),animations:'disabled'})
    assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth-innerWidth)<=1,'No document overflow')
    assert.equal(await modal.evaluate(node=>getComputedStyle(node).animationName),'none','Reduced motion covers body portal')
    report.cases.push({theme,width,control,icon,gutter,checkContrast:contrast(normal.mark,normal.background),portalMatchesShell:true,selectedHoverRetainsSelection:true})
    await context.close()
  }
  assert.deepEqual(report.errors,[])
} finally {
  await browser.close()
  await writeFile(path.join(out,'results.json'),JSON.stringify(report,null,2))
}
console.log(JSON.stringify({cases:report.cases.length,errors:report.errors,evidence:out}))
