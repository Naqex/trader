// Real label mutations are confined to the disposable Rust/PG bridge owned by trade_labels_acceptance.py.
import assert from 'node:assert/strict'
import { mkdir, writeFile } from 'node:fs/promises'
import { chromium } from 'playwright'

const [origin, out, bridge] = process.argv.slice(2)
for (const url of [origin, bridge]) assert.equal(new URL(url).hostname, '127.0.0.1')
assert.notEqual(new URL(origin).port, '5180')
await mkdir(out, { recursive: true })
const browser = await chromium.launch({ headless: true })
const report = { scope: 'disposable native Rust/PostgreSQL labels; synthetic live accounts; no broker', checks: [], errors: [], blockedWrites: [] }
const context = await browser.newContext({ viewport: { width: 1440, height: 940 }, reducedMotion: 'reduce' })
await context.addInitScript(() => { localStorage.setItem('tw-language', 'en'); if (!localStorage.getItem('tw-theme')) localStorage.setItem('tw-theme', 'dark') })
let holdRows = false
let releaseRows
const page = await context.newPage()
page.setDefaultTimeout(12000)
page.on('pageerror', error => report.errors.push(error.message))
const remote = async (path, method = 'GET', data) => {
  const response = await context.request.fetch(bridge + path, { method, headers: { 'X-Workspace-Id': 'tenant-a' }, ...(data ? { data } : {}) })
  assert.equal(response.ok(), true, `${method} ${path}: ${await response.text()}`)
  return response.json()
}
await context.route('**/*', async route => {
  const request = route.request(), url = new URL(request.url())
  if (url.origin !== origin) return route.abort()
  if (!url.pathname.startsWith('/api/')) return route.continue()
  if (url.pathname === '/api/v2/events') return route.fulfill({ status: 503, json: { detail: 'fixture_events_offline' } })
  if (!['GET','HEAD','OPTIONS'].includes(request.method()) && !(request.method() === 'POST' && url.pathname === '/api/v2/trade-labels')) {
    report.blockedWrites.push(url.pathname); return route.abort()
  }
  if (holdRows && url.pathname === '/api/v2/replay/trades') await new Promise(resolve => { releaseRows = resolve })
  return route.fulfill({ response: await route.fetch({ url: bridge + url.pathname + url.search }) })
})
try {
  const fixture = await remote('/fixture')
  const tradesApi = `/api/v2/replay/trades?page=1&page_size=10&sessions=${fixture.session_id}`
  const current = await remote(tradesApi)
  await remote('/api/v2/trade-labels','POST',{action:'assign',session_id:fixture.session_id,trade_id:fixture.trade_id,expected_revision:current.ledger[0].label_revision,tags:[]})
  const tradesUrl = `${origin}/?workspace=tenant-a&view=trade&lang=en&area=testing&section=trades&select=1&sessions=${fixture.session_id}`
  await page.goto(tradesUrl)
  const ledger = page.getByTestId('fx-trade-ledger')
  const cell = ledger.locator('.wm-label-cell').first()
  await cell.waitFor()
  assert.equal(await cell.locator('.wm-trade-label').count(),0)
  assert.equal(await cell.locator('.wm-label-placeholder').evaluate(el=>getComputedStyle(el).opacity),'0')
  await cell.hover()
  assert.equal(await cell.locator('.wm-label-placeholder').evaluate(el=>getComputedStyle(el).opacity),'1')
  await cell.click()
  const popup = page.getByRole('dialog',{name:'Trade labels',exact:true})
  await popup.getByRole('searchbox').fill('Trend fixture')
  await popup.getByRole('searchbox').press('Enter')
  await popup.getByRole('checkbox',{name:'Trend fixture',exact:true}).waitFor()
  await page.waitForFunction(()=>document.querySelector('.wm-label-cell')?.textContent.includes('Trend fixture'))
  assert.equal(await popup.isVisible(),true)
  await popup.getByRole('searchbox').fill('')
  // Hold parent ledger reads: consecutive selections must use the committed assignment revision.
  holdRows = true
  await popup.getByRole('checkbox',{name:'Momentum',exact:true}).click()
  await page.waitForFunction(()=>document.querySelector('.wm-label-selected')?.textContent.includes('Momentum'))
  await popup.getByRole('checkbox',{name:'New note label',exact:true}).click()
  await page.waitForFunction(()=>document.querySelector('.wm-label-selected')?.textContent.includes('New note label'))
  holdRows=false;releaseRows?.()
  const after = await remote(tradesApi)
  assert.deepEqual(after.ledger[0].tags,['Trend fixture','Momentum','New note label'])
  assert.equal(after.ledger[0].net_pnl,current.ledger[0].net_pnl)
  await page.keyboard.press('Escape')
  assert.equal(await cell.evaluate(el=>el===document.activeElement),true)
  await page.reload();await cell.waitFor()
  assert.match(await cell.innerText(),/Trend fixture/)
  report.checks.push('empty affordance, create via Enter, rapid multiple selection against real persisted revision, reload, Escape/focus return; finance unchanged')
  await cell.click()
  await popup.getByRole('button',{name:'Edit label Trend fixture',exact:true}).click()
  await popup.getByRole('textbox',{name:'Label name',exact:true}).fill('Renamed fixture')
  await popup.getByRole('button',{name:'Blue',exact:true}).click()
  await popup.getByRole('button',{name:'Save changes',exact:true}).click()
  await popup.getByRole('checkbox',{name:'Renamed fixture',exact:true}).waitFor()
  await page.keyboard.press('Escape')
  await page.waitForFunction(()=>document.querySelector('.wm-label-cell')?.textContent.includes('Renamed fixture'))
  assert.equal(await cell.locator('.wm-trade-label').filter({hasText:'Renamed fixture'}).getAttribute('data-color'),'blue')
  await cell.click()
  await popup.getByRole('button',{name:'Edit label Renamed fixture',exact:true}).click()
  await popup.getByRole('button',{name:'Delete label',exact:true}).click()
  await popup.getByRole('button',{name:'Delete label',exact:true}).click()
  await popup.getByRole('searchbox').waitFor()
  await page.keyboard.press('Escape')
  await page.reload();await cell.waitFor()
  assert.doesNotMatch(await cell.innerText(),/Renamed fixture|Trend fixture/)
  report.checks.push('global rename/color/delete and persisted reload')
  await page.screenshot({path:`${out}/trades-dark-1440.png`})
  for (const theme of ['light','dark']) {
    await page.evaluate(theme=>localStorage.setItem('tw-theme',theme),theme)
    await page.setViewportSize({width:390,height:844});await page.reload();await cell.waitFor()
    await cell.click();await popup.waitFor()
    assert.equal(await page.locator('.fx-app').getAttribute('data-theme'),theme)
    const rect=await popup.boundingBox()
    assert.ok(rect.x>=0 && rect.x+rect.width<=390 && rect.y>=0 && rect.y+rect.height<=844,JSON.stringify(rect))
    assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth))
    await page.screenshot({path:`${out}/labels-${theme}-390.png`})
    await page.keyboard.press('Escape')
  }
  report.checks.push('anchored popup fits mobile/light/dark; table owns horizontal scroll')
  await page.setViewportSize({width:1440,height:940})
  for (const source of ['backtest','prop','all']) {
    await page.goto(`${origin}/?workspace=tenant-a&view=overview&area=testing&section=dashboard&dashboard_source=${source}`)
    await page.locator('.fx-dashboard-results').waitFor()
    await page.waitForFunction(()=>document.querySelector('.fx-dashboard-results .report-chart'))
    assert.equal(await page.getByTestId('prop-analytics').count(),0)
    assert.equal(await page.locator('.fx-dashboard-results').count(),1)
    assert.equal(await page.locator('.fx-dashboard-results .report-chart').count(),3)
    await page.screenshot({path:`${out}/dashboard-${source}.png`})
  }
  report.checks.push('Backtest/Prop/All use the same report charts with native filtered data')
  await page.goto(`${origin}/?workspace=tenant-a&view=replay&area=testing&section=sessions&select=1&session=${fixture.session_id}`)
  const analytics=page.locator('.fxr-session-actions a').filter({hasText:'Analytics'})
  await analytics.waitFor()
  assert.equal(await analytics.getAttribute('aria-haspopup'),null)
  assert.equal(new URL(await analytics.getAttribute('href'),origin).searchParams.get('view'),'analytics')
  report.checks.push('session Analytics is a direct destination link')
  await page.goto(new URL(await analytics.getAttribute('href'),origin).href)
  const filters=page.getByTestId('analytics-filters')
  await filters.waitFor()
  await filters.getByRole('button',{name:'Side',exact:true}).click()
  const sides=page.getByRole('dialog',{name:'Side',exact:true})
  assert.equal(await sides.locator('.fx-filter-selection').innerText(),'All\n×')
  await sides.getByRole('option',{name:'Buy',exact:true}).click()
  await sides.getByRole('option',{name:'Sell',exact:true}).click()
  assert.equal(await sides.getByRole('option',{selected:true}).count(),2)
  await page.keyboard.press('Escape')
  await filters.getByRole('button',{name:'Apply',exact:true}).click()
  assert.deepEqual(JSON.parse(new URL(page.url()).searchParams.get('analytics_sides')),['buy','sell'])
  await page.reload();await filters.waitFor()
  await filters.getByRole('button',{name:'Side',exact:true}).click()
  assert.equal(await sides.getByRole('option',{selected:true}).count(),2)
  assert.equal(await sides.getByRole('searchbox').count(),1)
  report.checks.push('searchable checkbox filter selects multiple sides and persists applied scope on reload; empty selection displays All')
  assert.deepEqual(report.errors,[])
  assert.deepEqual(report.blockedWrites,[])
  report.status='PASS'
} catch(error) {
  report.status='FAIL';report.failure=String(error)
  await page.screenshot({path:`${out}/failure.png`}).catch(()=>{})
  throw error
} finally {
  holdRows=false;releaseRows?.()
  await context.unrouteAll({behavior:'ignoreErrors'})
  await writeFile(`${out}/report.json`,JSON.stringify(report,null,2))
  await browser.close()
}
console.log(JSON.stringify(report))
